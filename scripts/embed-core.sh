#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
output_path="$repo_root/selfhost/core_files.nl"
if [[ "${1:-}" == "--output" ]]; then
    [[ $# == 2 ]] || { echo "usage: scripts/embed-core.sh [--output <path>]" >&2; exit 2; }
    output_path="$2"
elif [[ $# != 0 ]]; then
    echo "usage: scripts/embed-core.sh [--output <path>]" >&2
    exit 2
fi

python3 - "$repo_root" "$output_path" <<'PY'
import hashlib
import pathlib
import sys

root = pathlib.Path(sys.argv[1])
output = pathlib.Path(sys.argv[2])
core = root / "core"
manifest = (core / "package.toml").read_text(encoding="utf-8")
state_bytes = None
for line in manifest.splitlines():
    key, sep, value = line.partition("=")
    if sep and key.strip() == "state_bytes":
        state_bytes = int(value.strip())
if state_bytes is None or state_bytes <= 0:
    raise SystemExit("core/package.toml must declare a positive state_bytes")

files = sorted((path for path in core.rglob("*.nl") if path.is_file()), key=lambda p: p.relative_to(core).as_posix())
if len(files) > 64:
    raise SystemExit("embedded core exceeds the 64-file budget")
payloads = [(path.relative_to(core).as_posix(), path.read_bytes()) for path in files]
total = sum(len(data) for _, data in payloads)
if total > 1024 * 1024:
    raise SystemExit("embedded core exceeds the 1 MiB source budget")

digest = hashlib.sha256()
for name, data in payloads:
    digest.update(name.encode("utf-8"))
    digest.update(b"\0")
    digest.update(data)
hash_hex = digest.hexdigest()
chunk_bytes = 512
lines = [
    "// Generated by scripts/embed-core.sh. Do not edit by hand.",
    f"fn embedded_core_file_count() -> long {{ {len(payloads)}L }}",
    f'fn embedded_core_hash() -> Ascii max 64 {{ "{hash_hex}" }}',
    f"fn embedded_core_state_bytes() -> long {{ {state_bytes}L }}",
]

lines.append("fn embedded_core_file_name(file: long) -> Ascii max 64 {")
for index, (name, _) in enumerate(payloads):
    lines.append(f'    if file == {index}L {{ "{name}" }}')
    if index + 1 < len(payloads):
        lines[-1] += " else"
    else:
        lines[-1] += ' else { "" }'
lines.append("}")

lines.append("fn embedded_core_chunk_count(file: long) -> long {")
for index, (_, data) in enumerate(payloads):
    count = (len(data) + chunk_bytes - 1) // chunk_bytes
    lines.append(f"    if file == {index}L {{ {count}L }} else")
lines.append("    { 0L }")
lines.append("}")

lines.append("fn embedded_core_file_chunk(file: long, chunk: long) -> Bytes max 4096 {")
for file_index, (_, data) in enumerate(payloads):
    chunks = [data[offset:offset + chunk_bytes] for offset in range(0, len(data), chunk_bytes)]
    if not chunks:
        chunks = [b""]
    lines.append(f"    if file == {file_index}L {{")
    for chunk_index, chunk in enumerate(chunks):
        encoded = "".join(f"\\x{byte:02x}" for byte in chunk)
        lines.append(f'        if chunk == {chunk_index}L {{ return b"{encoded}" }}')
    lines.append("    }")
lines.append('    return b""')
lines.append("}")

content = "\n".join(lines) + "\n"
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text(content, encoding="utf-8", newline="\n")
print(f"embedded {len(payloads)} core files ({total} bytes), sha256 {hash_hex}")
PY

#!/usr/bin/env python3
"""Generate selfhost/mailbox.nl (the compiler's copy of the mailbox ring) from selfhost/mailbox_ring.ll.
Usage: scripts/gen-mailbox-ir.py [--check]   (--check fails if the generated file is out of date)"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
source = root / "selfhost" / "mailbox_ring.ll"
target = root / "selfhost" / "mailbox.nl"


BS = chr(92)  # a backslash


def generate():
    out = ["// Generated by scripts/gen-mailbox-ir.py from selfhost/mailbox_ring.ll. Do not edit by hand.",
           "// The mailbox ring (many senders, one receiver) as internal LLVM IR, emitted into a program that uses a",
           "// mailbox. Its calls to @nl_park, @nl_wake and @nl.mem.copy are declared or defined elsewhere.",
           "",
           "fn emit_mailbox_functions(compiler: write CompilerTables, ir: grow Bytes max IR_BUFFER_CAPACITY) {"]
    for line in source.read_text().splitlines():
        if line.startswith(";") or line.startswith("declare ") or line.startswith("@nl_mbox_spin") or not line.strip():
            if not line.strip():
                out.append('    ir_write_ascii(compiler, ir, "' + BS + 'n")')
            continue
        escaped = line.replace(BS, BS + BS).replace('"', BS + '"')
        out.append(f'    ir_write_ascii(compiler, ir, "{escaped}{BS}n")')
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        if not target.is_file() or target.read_text() != text:
            sys.exit("selfhost/mailbox.nl is out of date; run scripts/gen-mailbox-ir.py")
    else:
        target.write_text(text, newline="\n")
        print(f"wrote {target.relative_to(root)}")
